#!/usr/bin/env python3
"""
assets.py

Recursively walks a directory and generates a C header file containing
#define macros mapping a symbolic name to each file's path, relative to
the current working directory.

Usage:
    python3 assets.py <asset_dir> [-o output.h]

Example:
    python3 assets.py res/ -o src/OrbitsAssets.h

Given a file at res/dark-knob-large.svg, this produces something like:

    #define ORBITS_ASSET_DARK_KNOB_LARGE_SVG "res/dark-knob-big-large.svg"
"""

import argparse
import os
import re
import sys
from pathlib import Path


def sanitize_to_macro_name(rel_path: Path, prefix: str) -> str:
    """Turn a relative path into a valid, readable C macro identifier."""
    # Use path without extension separators being special; keep extension
    # since it disambiguates e.g. knob.svg vs knob.png.
    s = str(rel_path.as_posix())

    # Replace any run of non-alphanumeric characters with a single underscore.
    s = re.sub(r'[^A-Za-z0-9]+', '_', s)

    s = s.strip('_').upper()

    name = f"{prefix}{s}"

    # C identifiers can't start with a digit.
    if name and name[0].isdigit():
        name = f"_{name}"

    return name


def collect_files(root: Path):
    """Yield all files under root, sorted for stable output."""
    files = [p for p in root.rglob('*') if p.is_file()]
    files.sort(key=lambda p: p.as_posix())
    return files


def build_header(asset_dir: Path, cwd: Path, prefix: str) -> str:
    files = collect_files(asset_dir)

    lines = []
    lines.append(f"// Auto-generated by assets.py - do not edit by hand.")
    lines.append(f"#pragma once")
    lines.append("")

    seen_names = {}
    for f in files:
        rel_to_cwd = os.path.relpath(f, cwd)
        rel_to_cwd_posix = Path(rel_to_cwd).as_posix()

        rel_for_name = f.relative_to(asset_dir)
        macro_name = sanitize_to_macro_name(rel_for_name, prefix)

        if macro_name in seen_names:
            print(
                f"warning: macro name collision for '{macro_name}' "
                f"({seen_names[macro_name]} vs {rel_to_cwd_posix}); skipping duplicate",
                file=sys.stderr,
            )
            continue
        seen_names[macro_name] = rel_to_cwd_posix

        lines.append(f'#define {macro_name} "{rel_to_cwd_posix}"')
    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Generate a C header of #defines for asset file paths.")
    parser.add_argument(
        "asset_dir", type=Path, nargs="?", default=Path("res"),
        help="Directory to scan recursively for asset files (default: res).",
    )
    parser.add_argument(
        "-o", "--output", type=Path, default=Path("src/OrbitsAssets.h"),
        help="Output header file path (default: src/OrbitsAssets.h)",
    )
    parser.add_argument(
        "--prefix", type=str, default="ORBITS_ASSET_",
        help="Prefix for each generated macro name (default: ORBITS_ASSET_).",
    )
    args = parser.parse_args()

    asset_dir = args.asset_dir.resolve()
    cwd = Path.cwd().resolve()

    if not asset_dir.is_dir():
        print(f"error: '{asset_dir}' is not a directory", file=sys.stderr)
        sys.exit(1)

    header_text = build_header(asset_dir, cwd, args.prefix)

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(header_text, encoding="utf-8")

if __name__ == "__main__":
    main()
